// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - runs as a plain Node maintainer script.
// Regenerates src/generated/ from Central Icons. Installing Central Icons requires
// CENTRAL_LICENSE_KEY, which `vp run --filter @supaterm/icons sync` reads from 1Password
// through fnox; everyone else uses the committed output.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodeModule from "node:module";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

interface Manifest {
  readonly version: string;
  readonly outlined: string;
  readonly filled: string;
  readonly icons: Readonly<Record<string, string>>;
  readonly project: ReadonlyArray<string>;
}

type Attrs = Record<string, string>;

const PACKAGE_DIR = NodeURL.fileURLToPath(new URL("..", import.meta.url));
const GENERATED_DIR = NodePath.join(PACKAGE_DIR, "src", "generated");
const HEADER =
  "// Generated by scripts/sync-central-icons.ts from Central Icons (see ../../LICENSE.md). Do not edit.";
const FILLED_PREFIX = "filled:";

const manifest: Manifest = JSON.parse(
  NodeFS.readFileSync(NodePath.join(PACKAGE_DIR, "icons.json"), "utf8"),
);

if (!process.env.CENTRAL_LICENSE_KEY) {
  console.error(
    "CENTRAL_LICENSE_KEY is not set. Run `vp run --filter @supaterm/icons sync`, which reads it from 1Password through fnox.",
  );
  process.exit(1);
}

const kebab = (name: string) => name.replaceAll(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const camel = (name: string) =>
  name.replaceAll(/-([a-z])/g, (_, letter: string) => letter.toUpperCase());

// Re-express one Central element relative to the defaults NodeIcon puts on <svg>.
function normalizeAttrs(source: Attrs): Attrs {
  const stroked = source.stroke !== undefined;
  const attrs: Attrs = {};
  for (const [key, value] of Object.entries(source)) {
    if (key === "stroke" && value === "currentColor") continue;
    if (key === "stroke-width" && value === "2") continue;
    if ((key === "stroke-linecap" || key === "stroke-linejoin") && value === "round") continue;
    attrs[camel(key)] = value;
  }
  if (!stroked) {
    attrs.stroke = "none";
    return attrs;
  }
  if (source["stroke-linecap"] === undefined) attrs.strokeLinecap = "butt";
  if (source["stroke-linejoin"] === undefined) attrs.strokeLinejoin = "miter";
  return attrs;
}

function parseMarkup(name: string, markup: string): Array<[string, Attrs]> {
  const body = markup.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  const elements: Array<[string, Attrs]> = [];
  for (const match of body.matchAll(/<([a-zA-Z]+)\b([^>]*?)\/?>/g)) {
    const tag = match[1];
    if (tag === undefined) continue;
    if (tag !== "path" && tag !== "circle") {
      throw new Error(`${name} uses <${tag}>, which NodeIcon does not render`);
    }
    const attrs: Attrs = {};
    for (const attr of (match[2] ?? "").matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
      if (attr[1] !== undefined && attr[2] !== undefined) attrs[attr[1]] = attr[2];
    }
    elements.push([tag, normalizeAttrs(attrs)]);
  }
  return elements;
}

function installCentral(dir: string): void {
  const packages = [manifest.outlined, manifest.filled].map(
    (style) => `@central-icons-react/${style}`,
  );
  NodeFS.writeFileSync(
    NodePath.join(dir, "package.json"),
    JSON.stringify({ name: "central-icons-sync", private: true }),
  );
  NodeFS.writeFileSync(
    NodePath.join(dir, "pnpm-workspace.yaml"),
    `allowBuilds:\n${packages.map((name) => `  "${name}": true`).join("\n")}\n`,
  );
  NodeChildProcess.execFileSync(
    "pnpm",
    ["add", ...packages.map((name) => `${name}@${manifest.version}`), "react@19", "react-dom@19"],
    { cwd: dir, stdio: "inherit" },
  );
}

const workDir = NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "central-icons-"));
try {
  installCentral(workDir);
  const requireFromWork = NodeModule.createRequire(NodePath.join(workDir, "package.json"));
  const { createElement } = requireFromWork("react");
  const { renderToStaticMarkup } = requireFromWork("react-dom/server");
  const outlined = requireFromWork(`@central-icons-react/${manifest.outlined}`);
  const filled = requireFromWork(`@central-icons-react/${manifest.filled}`);
  const index = JSON.parse(
    NodeFS.readFileSync(
      NodePath.join(
        workDir,
        "node_modules",
        "@central-icons-react",
        manifest.outlined,
        "icons-index.json",
      ),
      "utf8",
    ),
  );
  const aliases: Readonly<Record<string, string>> = index.iconAliases;

  const names = Object.keys(manifest.icons).toSorted();
  const nodes = new Map<string, Array<[string, Attrs]>>();
  for (const name of names) {
    const source = manifest.icons[name] ?? "";
    const isFilled = source.startsWith(FILLED_PREFIX);
    const centralName = `Icon${isFilled ? source.slice(FILLED_PREFIX.length) : source}`;
    const component = (isFilled ? filled : outlined)[centralName];
    if (!component) throw new Error(`${name}: Central Icons has no ${centralName}`);
    nodes.set(
      name,
      parseMarkup(name, renderToStaticMarkup(createElement(component, { mode: "raw" }))),
    );
  }

  const nodesFile = [
    HEADER,
    'import type { IconNode } from "../iconNode.ts";',
    "",
    ...names.map((name) => `export const ${name}: IconNode = ${JSON.stringify(nodes.get(name))};`),
    "",
  ].join("\n");

  const componentsFile = [
    HEADER,
    'import { createIcon } from "../createIcon.ts";',
    'import * as nodes from "./nodes.ts";',
    "",
    ...names.map(
      (name) =>
        `export const ${name}Icon = /* @__PURE__ */ createIcon("${name}Icon", nodes.${name});`,
    ),
    "",
  ].join("\n");

  const projectEntries = manifest.project.map((name) => {
    const source = (manifest.icons[name] ?? "").replace(FILLED_PREFIX, "");
    const words = [
      kebab(name).replaceAll("-", " "),
      ...(aliases[`Icon${source}`] ?? "").split(","),
    ];
    const keywords = [
      ...new Set(
        words.flatMap((word) =>
          word
            .trim()
            .toLowerCase()
            .split(/[\s-]+/),
        ),
      ),
    ]
      .filter((word) => word && !/^\d+$/.test(word))
      .join(" ");
    return `  { name: ${JSON.stringify(kebab(name))}, node: nodes.${name}, keywords: ${JSON.stringify(keywords)} },`;
  });
  const projectFile = [
    HEADER,
    'import type { ProjectIcon } from "../projectIcon.ts";',
    'import * as nodes from "./nodes.ts";',
    "",
    "export const PROJECT_ICONS: ReadonlyArray<ProjectIcon> = [",
    ...projectEntries,
    "];",
    "",
  ].join("\n");

  const files = {
    "nodes.ts": nodesFile,
    "components.ts": componentsFile,
    "projectIcons.ts": projectFile,
  };
  for (const [file, contents] of Object.entries(files))
    NodeFS.writeFileSync(NodePath.join(GENERATED_DIR, file), contents);
  NodeChildProcess.execFileSync("vp", ["fmt", GENERATED_DIR], { stdio: "inherit" });
  console.log(`Wrote ${names.length} icons and ${manifest.project.length} project icons.`);
} finally {
  NodeFS.rmSync(workDir, { recursive: true, force: true });
}
