// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - runs as a plain Node maintainer script.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as hugeicons from "@hugeicons/core-free-icons";
import { createCanvas, Path2D, PathOp } from "@napi-rs/canvas";
import svgpath from "svgpath";
import { ICON_STROKE_WIDTH, type IconNode } from "../src/iconNode.ts";
import { strokeOutline, tidyPath } from "./outline.ts";

type Selection = string | { icon: string; solid: true };
type Element = readonly [string, Readonly<Record<string, string | number>>];

const manifest: { icons: Record<string, Selection>; project: Record<string, string> } = JSON.parse(
  NodeFS.readFileSync(new URL("../icons.json", import.meta.url), "utf8"),
);
const catalog: Readonly<Record<string, ReadonlyArray<Element> | undefined>> = hugeicons;
const header = "// Generated by scripts/sync-icons.ts. Do not edit.";
const kebab = (name: string) => name.replaceAll(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const sourceIcon = (selection: Selection) =>
  typeof selection === "string" ? selection : selection.icon;
const hitTest = createCanvas(24, 24).getContext("2d");

function ellipse(cx: number, cy: number, rx: number, ry: number) {
  return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0Z`;
}

function elementShape(icon: string, [tag, attrs]: Element): string {
  const number = (key: string) => Number(attrs[key] ?? 0);
  switch (tag) {
    case "path":
      return String(attrs.d);
    case "circle":
      return ellipse(number("cx"), number("cy"), number("r"), number("r"));
    case "ellipse":
      return ellipse(number("cx"), number("cy"), number("rx"), number("ry"));
    default:
      throw new Error(`${icon} uses an unsupported <${tag}> element`);
  }
}

function elementPath(icon: string, element: Element): string {
  const path = svgpath(elementShape(icon, element)).abs();
  const { transform } = element[1];
  if (transform !== undefined) path.transform(String(transform));
  return tidyPath(path.toString());
}

function outlineNode(icon: string, elements: ReadonlyArray<Element>): IconNode {
  const stroke: Array<string> = [];
  const fill: Array<string> = [];
  for (const element of elements) {
    const attrs = element[1];
    const stroked = attrs.stroke !== undefined;
    const filled = attrs.fill !== undefined && attrs.fill !== "none";
    if (!stroked && !filled) throw new Error(`${icon} has an element with no paint`);
    if (stroked && Number(attrs.strokeWidth) !== ICON_STROKE_WIDTH) {
      throw new Error(`${icon} has a ${attrs.strokeWidth} stroke; icons share one stroke width`);
    }
    if (attrs.opacity !== undefined || (filled && attrs.fillRule !== undefined)) {
      throw new Error(`${icon} needs opacity or a fill rule, which icon nodes cannot carry`);
    }
    const path = elementPath(icon, element);
    if (stroked) stroke.push(path);
    if (filled) fill.push(path);
  }
  const node: { stroke?: string; fill?: string } = {};
  if (stroke.length > 0) node.stroke = stroke.join("");
  if (fill.length > 0) {
    const body = new Path2D();
    for (const shape of fill) body.op(new Path2D(shape), PathOp.Union);
    node.fill = tidyPath(body.toSVGString());
  }
  return node;
}

// Shapes are filled largest first. One drawn inside an area that is already filled is detail
// and is cut out, the way a filled warning triangle keeps its exclamation mark.
function solidNode(icon: string, elements: ReadonlyArray<Element>): IconNode {
  const shapes = elements
    .map((element) => {
      const shape = elementPath(icon, element);
      const outline = strokeOutline(shape);
      const [left, top, right, bottom] = outline.computeTightBounds();
      return {
        shape,
        outline,
        closed: /z\s*$/i.test(shape),
        area: (right - left) * (bottom - top),
        centerX: (left + right) / 2,
        centerY: (top + bottom) / 2,
      };
    })
    .toSorted((left, right) => right.area - left.area);
  const body = new Path2D();
  const filled: Array<Path2D> = [];
  for (const { shape, outline, closed, centerX, centerY } of shapes) {
    if (filled.some((area) => hitTest.isPointInPath(area, centerX, centerY))) {
      body.op(outline, PathOp.Difference);
      continue;
    }
    body.op(outline, PathOp.Union);
    if (closed) {
      body.op(new Path2D(shape), PathOp.Union);
      filled.push(new Path2D(shape));
    }
  }
  return { fill: tidyPath(body.toSVGString()) };
}

const nodes = [header, 'import type { IconNode } from "../iconNode.ts";'];
const components = [
  header,
  'import { createIcon } from "../createIcon.ts";',
  'import * as nodes from "./nodes.ts";',
];
const projects = [
  header,
  'import type { ProjectIcon } from "../projectIcon.ts";',
  'import * as nodes from "./nodes.ts";',
  "export const PROJECT_ICONS: ReadonlyArray<ProjectIcon> = [",
];

for (const [name, selection] of Object.entries(manifest.icons)) {
  const icon = sourceIcon(selection);
  const elements = catalog[`${icon}Icon`];
  if (elements === undefined) throw new Error(`Unknown Hugeicons icon: ${icon}`);
  const node =
    typeof selection === "string" ? outlineNode(icon, elements) : solidNode(icon, elements);
  nodes.push(`export const ${name} = ${JSON.stringify(node)} satisfies IconNode;`);
  components.push(
    `export const ${name}Icon = /* @__PURE__ */ createIcon(${JSON.stringify(name)}, nodes.${name});`,
  );
}
for (const [name, extraKeywords] of Object.entries(manifest.project)) {
  const selection = manifest.icons[name];
  if (selection === undefined) throw new Error(`Unknown project icon: ${name}`);
  const keywords = [
    ...new Set(
      `${kebab(name)} ${kebab(sourceIcon(selection))} ${extraKeywords}`
        .toLowerCase()
        .split(/[-\s]+/)
        .filter((word) => word !== ""),
    ),
  ].join(" ");
  projects.push(
    `{ name: "${kebab(name)}", node: nodes.${name}, keywords: ${JSON.stringify(keywords)} },`,
  );
}
projects.push("];");
for (const [name, lines] of Object.entries({ nodes, components, projectIcons: projects })) {
  NodeFS.writeFileSync(
    new URL(`../src/generated/${name}.ts`, import.meta.url),
    `${lines.join("\n")}\n`,
  );
}
NodeChildProcess.execFileSync("vp", ["fmt", "packages/icons/src/generated"], {
  cwd: new URL("../../../", import.meta.url),
  stdio: "inherit",
});
console.log(
  `Generated ${Object.keys(manifest.icons).length} icons and ${Object.keys(manifest.project).length} project icons.`,
);
