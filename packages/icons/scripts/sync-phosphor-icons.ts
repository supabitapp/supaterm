// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - runs as a plain Node maintainer script.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import { icons as catalog } from "@phosphor-icons/core";
import type { IconProps } from "@phosphor-icons/react";
import svgpath from "svgpath";

type Selection = string | { icon: string; props: Partial<Pick<IconProps, "weight" | "mirrored">> };
const manifest: { icons: Record<string, Selection>; project: string[] } = JSON.parse(
  NodeFS.readFileSync(new URL("../icons.json", import.meta.url), "utf8"),
);
const header = "// Generated by scripts/sync-phosphor-icons.ts. Do not edit.";
const kebab = (name: string) => name.replaceAll(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const nodes = [header, 'import type { IconNode } from "../iconNode.ts";'];
const components = [header, 'import { withIconDefaults } from "../withIconDefaults.ts";'];
const projects = [
  header,
  'import type { ProjectIcon } from "../projectIcon.ts";',
  'import * as nodes from "./nodes.ts";',
  "export const PROJECT_ICONS: ReadonlyArray<ProjectIcon> = [",
];

for (const [name, selection] of Object.entries(manifest.icons)) {
  const icon = typeof selection === "string" ? selection : selection.icon;
  const props: Partial<Pick<IconProps, "weight" | "mirrored">> =
    typeof selection === "string" ? {} : selection.props;
  const metadata = catalog.find((entry) => entry.pascal_name === icon);
  if (!metadata) throw new Error(`Unknown Phosphor icon: ${icon}`);
  const weight = props.weight ?? "regular";
  const filename = `${metadata.name}${weight === "regular" ? "" : `-${weight}`}.svg`;
  const markup = NodeFS.readFileSync(
    new URL(import.meta.resolve(`@phosphor-icons/core/assets/${weight}/${filename}`)),
    "utf8",
  );
  const body = markup
    .trim()
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .trim();
  const match = /^<path\s+d="([^"]+)"\s*\/>$/.exec(body);
  if (!match?.[1]) throw new Error(`${icon} must contain one unstyled SVG path`);
  const path = svgpath(match[1]).scale(24 / 256);
  if (props.mirrored) path.scale(-1, 1).translate(24, 0);
  nodes.push(`export const ${name}: IconNode = ${JSON.stringify(path.round(5).toString())};`);
  const source = `@phosphor-icons/react/dist/csr/${icon}`;
  const defaults = Object.keys(props).length ? `, ${JSON.stringify(props)}` : "";
  components.push(
    `import { ${icon}Icon as ${name}Source } from "${source}";`,
    `export const ${name}Icon = /* @__PURE__ */ withIconDefaults(${name}Source${defaults});`,
  );
}
for (const name of manifest.project) {
  const selection = manifest.icons[name];
  if (!selection) throw new Error(`Unknown project icon: ${name}`);
  const source = typeof selection === "string" ? selection : selection.icon;
  const metadata = catalog.find((entry) => entry.pascal_name === source);
  const keywords = [
    ...new Set(
      `${kebab(name)} ${kebab(source)} ${metadata?.tags.join(" ") ?? ""}`
        .toLowerCase()
        .split(/[-\s]+/),
    ),
  ].join(" ");
  projects.push(
    `{ name: "${kebab(name)}", node: nodes.${name}, keywords: ${JSON.stringify(keywords)} },`,
  );
}
projects.push("];");
for (const [name, lines] of Object.entries({ nodes, components, projectIcons: projects })) {
  NodeFS.writeFileSync(
    new URL(`../src/generated/${name}.ts`, import.meta.url),
    `${lines.join("\n")}\n`,
  );
}
NodeChildProcess.execFileSync("vp", ["fmt", "packages/icons/src/generated"], {
  cwd: new URL("../../../", import.meta.url),
  stdio: "inherit",
});
console.log(
  `Generated ${Object.keys(manifest.icons).length} icons and ${manifest.project.length} project icons.`,
);
